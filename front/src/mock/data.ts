export const mockApi = {
  getPhotos: (params?: { city?: string; sort?: 'newest' | 'oldest' }): Promise<Photo[]> => {
    let photos = [...mockPhotos];
    if (params?.city) {
      photos = photos.filter((p) => p.city === params.city);
    }
    if (params?.sort) {
      photos.sort((a, b) => {
        const d = new Date(a.takenAt).getTime() - new Date(b.takenAt).getTime();
        return params.sort === 'oldest' ? d : -d;
      });
    }
    return Promise.resolve(photos);
  },

  getPhotoById: (id: string): Promise<Photo | undefined> => {
    return Promise.resolve(mockPhotos.find((p) => p.id === id));
  },

  getCities: (): Promise<City[]> => {
    return Promise.resolve([...mockCities].sort((a, b) => a.name.localeCompare(b.name)));
  },

  getPhotosByCity: (cityName: string): Promise<Photo[]> => {
    return Promise.resolve(mockPhotos.filter((p) => p.city === cityName));
  },

  getFeaturedPhotos: (): Promise<Photo[]> => {
    const featured = mockPhotos.filter((_, i) => i % 3 === 0).slice(0, 15);
    return Promise.resolve(featured);
  },
};
