function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function photo(
  id: number,
  title: string,
  city: string,
  country: string,
  lat: number,
  lng: number,
  takenAt: string,
  description: string,
  overrides?: Partial<Photo>,
): Photo {
  const cam = pick(cameras);
  const apertures = ['f/1.4', 'f/2.8', 'f/4', 'f/5.6', 'f/8', 'f/11'];
  const shutters = ['1/125s', '1/250s', '1/500s', '1/1000s', '1/60s', '1/30s'];
  const isos = [100, 200, 400, 800, 1600, 3200];
  return {
    id: String(id),
    title,
    url: img(id),
    thumbnailUrl: thumb(id),
    city,
    country,
    latitude: lat + (Math.random() - 0.5) * 0.02,
    longitude: lng + (Math.random() - 0.5) * 0.02,
    takenAt,
    camera: cam.camera,
    lens: cam.lens,
    aperture: pick(apertures),
    shutter: pick(shutters),
    iso: pick(isos),
    description,
    ...overrides,
  };
}

